// Package nodeattestor contains the protocol shared by the agent and server cmc node attestors.
//
// The attestation is a challenge-response exchange:
//  1. agent sends Payload
//  2. server sends a fresh nonce as challenge
//  3. agent returns the attestation report generated by cmcd for this nonce. The report carries
//     the node ID as claim ClaimNodeId, which binds it to the hardware evidence
package nodeattestor

import (
	"fmt"

	"github.com/google/uuid"
)

const (
	// PluginName is the SPIRE plugin name and selector type
	PluginName = "cmc"

	// Version is the protocol version
	Version = "1.0.0"

	// ClaimNodeId is the report claim carrying the node ID
	ClaimNodeId = "spire.cmc.node-id"

	// NonceLen is the length of the challenge nonce in bytes
	NonceLen = 32
)

// Payload is the initial attestation payload sent by the agent
type Payload struct {
	Version string `json:"version"`
}

// ParseNodeId validates that id is a UUID in canonical form, so that it can safely be used as
// SPIFFE ID path segment
func ParseNodeId(id string) (string, error) {
	u, err := uuid.Parse(id)
	if err != nil {
		return "", fmt.Errorf("invalid node ID %q: %w", id, err)
	}
	if u.String() != id {
		return "", fmt.Errorf("node ID %q is not in canonical form", id)
	}
	return id, nil
}
